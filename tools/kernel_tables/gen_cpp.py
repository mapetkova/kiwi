"""Generate src/kernel_spec_data.cpp (the coefficient tables used by the C++ generic kernel integral).

Usage: python3 gen_cpp.py            write ../../src/kernel_spec_data.cpp
       python3 gen_cpp.py --check    exit 1 if the committed file differs from what would be generated
"""
import os, sys
from fractions import Fraction as Fr
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kernels import KERNELS
from derive import derive_3d

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "src", "kernel_spec_data.cpp")
NI, NB, NR = 15, 16, 4
RADKERN = {"M4": 2.0, "M5": 2.5, "M6": 3.0, "WC2": 2.0, "WC4": 2.0, "WC6": 2.0}
ALIASES = {"M4": ["cubic", "cubic_spline", "m4"], "M5": ["quartic", "quartic_spline", "m5"],
           "M6": ["quintic", "quintic_spline", "m6"], "WC2": ["wendland_c2", "wendlandc2", "wc2"],
           "WC4": ["wendland_c4", "wendlandc4", "wc4"], "WC6": ["wendland_c6", "wendlandc6", "wc6"]}

def num(x):
    return repr(float(x))

def block(key, K):
    a, B = derive_3d(K)
    nreg = len(K.breaks) + 1
    assert nreg <= NR
    lines = [f"    {{ // {K.name}", f'        "{key}", "{K.name}", {nreg},']
    cs = [num(c) for c in K.breaks] + ["0.0"] * (NR - len(K.breaks))
    lines.append("        {" + ", ".join(cs) + "},")
    lines.append(f"        {num(K.norm(2))}, {num(K.norm(3))}, {RADKERN[key]},")
    rows = []
    for k in range(1, NR + 1):
        row = [Fr(0)] * NI
        for i, v in a.get(k, {}).items():
            assert 1 - i < NI and i != 0, (key, i)
            row[1 - i] = v
        rows.append("{" + ", ".join(num(v) for v in row) + "}")
    lines.append("        {" + ",\n         ".join(rows) + "},")
    jrows = []
    for j in range(1, NR + 1):
        krows = []
        for k in range(1, NR + 1):
            poly = B.get((j, k), {})
            row = [Fr(0)] * NB
            for p, v in poly.items():
                assert 0 <= p < NB, (key, j, k, p)
                row[p] = v
            krows.append("{" + ", ".join(num(v) for v in row) + "}")
        jrows.append("{" + ",\n          ".join(krows) + "}")
    lines.append("        {" + ",\n         ".join(jrows) + "}")
    lines.append("    },")
    return "\n".join(lines)

def generate():
    out = ["// GENERATED by tools/kernel_tables/gen_cpp.py -- do not edit by hand.",
           "// Exact coefficient tables for the six kernels of thesis appendix A, see kiwi/kernel_spec.hpp.",
           "#include \"kiwi/kernel_spec.hpp\"", "", "#include <algorithm>", "#include <cctype>",
           "#include <stdexcept>", "", "namespace kiwi {", "", "namespace {",
           "const KernelSpec kKernels[] = {"]
    out += [block(k, K) for k, K in KERNELS.items()]
    out += ["};", "} // namespace", "",
            "const std::vector<const KernelSpec*>& all_kernels() {",
            "    static const std::vector<const KernelSpec*> v = [] {",
            "        std::vector<const KernelSpec*> r;",
            "        for (const auto& k : kKernels) r.push_back(&k);",
            "        return r;",
            "    }();", "    return v;", "}", "",
            "const KernelSpec& get_kernel(const std::string& name) {",
            "    std::string n = name;",
            "    std::transform(n.begin(), n.end(), n.begin(), [](unsigned char ch) { return std::tolower(ch); });",
            "    std::replace(n.begin(), n.end(), '-', '_');", "    std::replace(n.begin(), n.end(), ' ', '_');"]
    for key, al in ALIASES.items():
        names = " || ".join(f'n == "{x}"' for x in al)
        idx = list(KERNELS).index(key)
        out.append(f"    if ({names}) return kKernels[{idx}];")
    out += ['    throw std::invalid_argument("unknown kernel \'" + name + "\' (expected one of: cubic_spline, quartic_spline, quintic_spline, wendland_c2, wendland_c4, wendland_c6)");',
            "}", "", "} // namespace kiwi", ""]
    return "\n".join(out)

if __name__ == "__main__":
    text = generate()
    path = os.path.normpath(OUT)
    if "--check" in sys.argv:
        cur = open(path).read() if os.path.exists(path) else ""
        if cur != text:
            print("src/kernel_spec_data.cpp is out of date: run tools/kernel_tables/gen_cpp.py"); sys.exit(1)
        print("src/kernel_spec_data.cpp is up to date")
    else:
        open(path, "w").write(text); print("wrote", path)
